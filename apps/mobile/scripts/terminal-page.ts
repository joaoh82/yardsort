/**
 * Build the terminal's page (`terminal/page.ts`, xterm.js and its styles) into one document, kept in
 * `src/ui/terminal-page.generated.ts`. A test says when that is out of date. Run with `bun`:
 * `just mobile-terminal-page`.
 *
 * The document may run its own script and nothing else, and may connect to nothing, which its
 * Content-Security-Policy holds it to. xterm.js sets styles of its own, hence `unsafe-inline` there.
 */

import { createHash } from "node:crypto";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
export const GENERATED = join(ROOT, "src/ui/terminal-page.generated.ts");

const PAGE_STYLE = `
html, body { margin: 0; background: #151514; }
#terminal { display: inline-block; vertical-align: top; }
`;

/** The document, and the source file that holds it. */
export async function buildPage(): Promise<{ html: string; source: string }> {
  const built = await Bun.build({
    entrypoints: [join(ROOT, "terminal/page.ts")],
    target: "browser",
    format: "iife",
    minify: true,
    throw: true,
  });
  const script = (await built.outputs[0]?.text())?.replaceAll("</script", "<\\/script");
  if (!script) throw new Error("The page built to nothing.");
  const xterm = await Bun.file(join(ROOT, "node_modules/@xterm/xterm/css/xterm.css")).text();
  const hash = createHash("sha256").update(script).digest("base64");
  const policy = [
    "default-src 'none'",
    `script-src 'sha256-${hash}'`,
    "style-src 'unsafe-inline'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join("; ");
  const html = [
    "<!doctype html><html><head><meta charset=utf-8>",
    `<meta http-equiv=Content-Security-Policy content="${policy}">`,
    '<meta name=viewport content="width=device-width,initial-scale=1,minimum-scale=1,maximum-scale=4">',
    `<style>${xterm}${PAGE_STYLE}</style></head>`,
    `<body><div id=terminal></div><script>${script}</script></body></html>`,
  ].join("");
  const source = [
    "// Generated by scripts/terminal-page.ts. Do not edit it: run `just mobile-terminal-page`.",
    `export const TERMINAL_PAGE = ${JSON.stringify(html)};`,
    "",
  ].join("\n");
  return { html, source };
}

if (import.meta.main) {
  const { source } = await buildPage();
  await Bun.write(GENERATED, source);
  console.log(`terminal page: ${Math.round(source.length / 1024)} KB`);
}
